export function tenantBySlug(slug: string): WhitelabelTenant | undefined {
  return WHITELABEL_TENANTS.find((t) => t.slug === slug);
}

export function productionTenants(): WhitelabelTenant[] {
  return WHITELABEL_TENANTS.filter((t) => t.mode === 'production');
}

export function demoTenants(): WhitelabelTenant[] {
  return WHITELABEL_TENANTS;
}

export function resolveTenantFromHostname(hostname: string): WhitelabelTenant | undefined {
  const host = hostname.toLowerCase().replace(/^www\./, '');
  return WHITELABEL_TENANTS.find((t) => t.portalHost?.toLowerCase() === host);
}
